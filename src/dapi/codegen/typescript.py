"""TypeScript (fetch-based, Node 18+/Deno/Bun) client generator."""

from __future__ import annotations

import json
import re
from typing import Any

from dapi.codegen.spec import ClientSpec, Operation, TokenFlow, pascal
from dapi.codegen.types import TypeRegistry

PRIM = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}
IDENT_RE = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def ts_type(node: Any) -> str:
    kind = node[0]
    if kind == "prim":
        return PRIM[node[1]]
    if kind == "list":
        inner = ts_type(node[1])
        return f"Array<{inner}>"
    if kind == "map":
        return f"Record<string, {ts_type(node[1])}>"
    if kind == "model":
        return node[1]
    if kind == "union":
        parts = list(dict.fromkeys(ts_type(n) for n in node[1]))
        return "unknown" if "unknown" in parts else " | ".join(sorted(parts, key=lambda p: p == "null"))
    return "unknown"


def camel(name: str) -> str:
    parts = name.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def _key(k: str) -> str:
    return k if IDENT_RE.match(k) else json.dumps(k)


def _param_type(t: str) -> str:
    return {"integer": "number", "number": "number", "boolean": "boolean"}.get(t, "string")


def _flow_literal(tf: TokenFlow | None) -> str:
    if tf is None:
        return "null"
    return json.dumps(
        {
            "method": tf.method,
            "path": tf.path,
            "bodyKind": tf.body_kind,
            "template": tf.template,
            "accessTokenPath": tf.access_token_path,
            "refreshTokenPath": tf.refresh_token_path,
            "expiresInPath": tf.expires_in_path,
            "secretParams": tf.secret_params,
            "prerequisites": tf.prerequisites,
            "evidenceFlows": tf.evidence,
        },
        indent=2,
    )


def generate_typescript(spec: ClientSpec) -> str:
    reg = TypeRegistry()
    op_types: dict[str, tuple[str, str | None]] = {}
    for op in spec.operations:
        resp = (
            ts_type(reg.node(op.response_schema, pascal(op.name) + "Response"))
            if op.response_kind == "json"
            else ("void" if op.response_kind == "empty" else "string")
        )
        body = ts_type(reg.node(op.body_schema, pascal(op.name) + "Request")) if op.body_kind else None
        op_types[op.name] = (resp, body)
    a = spec.auth
    out: list[str] = []
    w = out.append
    w("/**\n")
    w(
        f" * {spec.title} API client -- generated by dapi from {spec.flow_count} observed flows of {spec.origin}.\n"
    )
    w(
        " *\n * Every method corresponds to an endpoint seen in captured traffic; doc comments cite the flows\n"
    )
    w(" * that evidence it. Credentials are never embedded: pass them in or use fromEnv().\n")
    w(" * Targets Node 18+, Deno and Bun (uses fetch; manages cookies itself).\n")
    w(f" * Regenerate: dapi generate --lang typescript --origin {spec.origin}\n */\n\n")
    w("/* eslint-disable */\n\n")
    w(f"export const BASE_URL = {json.dumps(spec.origin)};\n")
    w(f"export const ENV_PREFIX = {json.dumps(spec.env_prefix)};\n")
    w(f"const AUTH_KIND = {json.dumps(a.kind)} as string; // inferred from observed traffic\n")
    w(f"const AUTH_HEADER: string | null = {json.dumps(a.header_name)};\n")
    w(f"const AUTH_SCHEME: string | null = {json.dumps(a.scheme)};\n")
    w(f"const AUTH_QUERY_PARAM: string | null = {json.dumps(a.query_name)};\n")
    w(f"const LOGIN_FLOW: TokenFlow | null = {_flow_literal(a.login)};\n")
    w(f"const REFRESH_FLOW: TokenFlow | null = {_flow_literal(a.refresh)};\n")
    w(f"const SESSION_COOKIES: string[] = {json.dumps(a.cookie_names)};\n")
    gql_docs = {
        o.graphql["operation_name"]: {
            "query": o.graphql.get("document"),
            "extensions": o.graphql.get("extensions"),
        }
        for o in spec.operations
        if o.graphql
    }
    w(
        f"const GRAPHQL_OPERATIONS: Record<string, {{ query: string | null; extensions: unknown }}> = {json.dumps(gql_docs, indent=2)};\n"
    )
    w(
        f"const CSRF_PAIRS: Array<{{ header: string; cookie: string }}> = {json.dumps(a.csrf)}; // header <- cookie echo\n\n"
    )
    if a.notes:
        w("// Auth evidence (from dapi auth analysis):\n")
        for n in a.notes[:12]:
            w(f"//   - {n}\n")
        w("\n")
    w("// ---- Models inferred from observed payloads (keys absent in some samples are optional) ----\n\n")
    for m in reg.models:
        w(f"export interface {m.name} {{\n")
        for k, t, req in m.fields:
            w(f"  {_key(k)}{'' if req else '?'}: {ts_type(t)};\n")
        w("}\n\n")
    w(RUNTIME.replace("__CLASS__", spec.class_name))
    for op in spec.operations:
        w(_render_op(op, *op_types[op.name]))
    w("}\n")
    return "".join(out)


def _render_graphql_op(op: Operation, resp_type: str, body_type: str | None) -> str:
    g = op.graphql or {}
    var_type = body_type or "Record<string, unknown>"
    opt = "" if op.body_required else "?"
    doc = "\n".join(f"   * {line}".rstrip() for line in op.doc).replace("*/", "* /")
    auth = "false" if op.auth_required == "no" else "true"
    return (
        f"\n  /**\n{doc}\n   */\n"
        f"  async {camel(op.name)}(variables{opt}: {var_type}): Promise<{resp_type}> {{\n"
        f"    return this.graphql({json.dumps(op.method)}, {json.dumps(op.path)}, {json.dumps(g['operation_name'])}, variables, {auth}) as Promise<{resp_type}>;\n"
        f"  }}\n"
    )


def _render_op(op: Operation, resp_type: str, body_type: str | None) -> str:
    if op.graphql:
        return _render_graphql_op(op, resp_type, body_type)
    args = [f"{camel(p.name)}: {_param_type(p.type)} | string" for p in op.path_params]
    if op.body_kind:
        args.append(f"body: {body_type or 'Record<string, unknown>'}")
    opts = [f"{_key(camel(q.name))}?: {_param_type(q.type)}" for q in op.query_params]
    opts.append("extraParams?: Record<string, string | number | boolean>")
    args.append("options: { " + "; ".join(opts) + " } = {}")
    path_expr = op.path
    for p in op.path_params:
        path_expr = path_expr.replace("{" + p.wire + "}", "${seg(" + camel(p.name) + ")}")
    doc = "\n".join(f"   * {line}".rstrip() for line in op.doc).replace("*/", "* /")
    query = ", ".join(f"{json.dumps(q.wire)}: options.{camel(q.name)}" for q in op.query_params)
    body = ", body" if op.body_kind else ""
    kind = json.dumps(op.body_kind) if op.body_kind else "undefined"
    auth = "false" if op.auth_required == "no" else "true"
    return (
        f"\n  /**\n{doc}\n   */\n"
        f"  async {camel(op.name)}({', '.join(args)}): Promise<{resp_type}> {{\n"
        f"    return this.request({json.dumps(op.method)}, `{path_expr}`, {{ query: {{ {query}{', ' if query else ''}...options.extraParams }}{body}, bodyKind: {kind}, auth: {auth}, expect: {json.dumps(op.response_kind)} }}) as Promise<{resp_type}>;\n"
        f"  }}\n"
    )


RUNTIME = r"""interface TokenFlow {
  method: string;
  path: string;
  bodyKind: "json" | "form";
  template: unknown;
  accessTokenPath: string[] | null;
  refreshTokenPath: string[] | null;
  expiresInPath: string[] | null;
  secretParams: string[];
  prerequisites: Array<{ method: string; path: string; values: Record<string, { cookie?: string; json?: string[] }>; evidence: number[] }>;
  evidenceFlows: number[];
}

export interface ClientOptions {
  baseUrl?: string;
  token?: string;
  refreshToken?: string;
  username?: string;
  password?: string;
  cookies?: Record<string, string>;
  headers?: Record<string, string>;
  secrets?: Record<string, string>;
  autoRefresh?: boolean;
  fetch?: typeof fetch;
}

interface RequestOptions {
  query?: Record<string, unknown>;
  body?: unknown;
  bodyKind?: "json" | "form";
  auth?: boolean;
  expect?: "json" | "text" | "empty";
}

export class GraphQLError extends Error {
  constructor(public readonly operation: string, public readonly errors: unknown[]) {
    super(`${operation}: ${JSON.stringify(errors).slice(0, 300)}`);
  }
}

export class ApiError extends Error {
  constructor(public readonly status: number, public readonly body: string, method: string, path: string) {
    super(`${method} ${path} -> ${status}: ${body.slice(0, 300)}`);
  }
}

const seg = (v: unknown): string => encodeURIComponent(String(v));

function getPath(data: unknown, path: string[] | null): unknown {
  if (!path) return undefined;
  let cur: unknown = data;
  for (const key of path) {
    if (cur === null || typeof cur !== "object") return undefined;
    cur = (cur as Record<string, unknown>)[key];
  }
  return cur;
}

function fill(template: unknown, values: Record<string, unknown>): unknown {
  if (Array.isArray(template)) return template.map((v) => fill(v, values));
  if (template && typeof template === "object") {
    return Object.fromEntries(Object.entries(template).map(([k, v]) => [k, fill(v, values)]));
  }
  if (typeof template === "string" && template.startsWith("{{") && template.endsWith("}}")) {
    const key = template.slice(2, -2);
    if (values[key] === undefined || values[key] === null) throw new Error(`missing value for ${key}`);
    return values[key];
  }
  return template;
}

function jwtExp(token?: string): number | undefined {
  try {
    const payload = token!.split(".")[1];
    const b64 = payload.replace(/-/g, "+").replace(/_/g, "/") + "=".repeat((4 - (payload.length % 4)) % 4);
    const json = JSON.parse((globalThis as any).atob(b64));
    return typeof json.exp === "number" ? json.exp * 1000 : undefined;
  } catch {
    return undefined;
  }
}

export class __CLASS__ {
  baseUrl: string;
  token?: string;
  refreshToken?: string;
  username?: string;
  password?: string;
  tokenExpiresAt?: number;
  cookies: Record<string, string>;
  headers: Record<string, string>;
  secrets: Record<string, string>;
  autoRefresh: boolean;
  private fetchImpl: typeof fetch;

  constructor(options: ClientOptions = {}) {
    this.baseUrl = (options.baseUrl ?? BASE_URL).replace(/\/$/, "");
    this.token = options.token;
    this.refreshToken = options.refreshToken;
    this.username = options.username;
    this.password = options.password;
    this.cookies = { ...(options.cookies ?? {}) };
    this.headers = { ...(options.headers ?? {}) };
    this.secrets = { ...(options.secrets ?? {}) };
    this.autoRefresh = options.autoRefresh ?? true;
    this.fetchImpl = options.fetch ?? fetch;
    this.tokenExpiresAt = jwtExp(this.token);
  }

  /** Read <PREFIX>_BASE_URL, _TOKEN, _REFRESH_TOKEN, _USERNAME, _PASSWORD, _COOKIES, _HEADERS (JSON), _SECRET_<NAME>. */
  static fromEnv(prefix: string = ENV_PREFIX, env: Record<string, string | undefined> = (globalThis as any).process?.env ?? {}): __CLASS__ {
    const cookies: Record<string, string> = {};
    for (const part of (env[`${prefix}_COOKIES`] ?? "").split(";")) {
      const i = part.indexOf("=");
      if (i > 0) cookies[part.slice(0, i).trim()] = part.slice(i + 1).trim();
    }
    const secrets: Record<string, string> = {};
    for (const [k, v] of Object.entries(env)) {
      if (k.startsWith(`${prefix}_SECRET_`) && v) secrets[k.slice(prefix.length + 8).toLowerCase()] = v;
    }
    return new __CLASS__({
      baseUrl: env[`${prefix}_BASE_URL`] ?? BASE_URL,
      token: env[`${prefix}_TOKEN`],
      refreshToken: env[`${prefix}_REFRESH_TOKEN`],
      username: env[`${prefix}_USERNAME`],
      password: env[`${prefix}_PASSWORD`],
      cookies,
      headers: env[`${prefix}_HEADERS`] ? JSON.parse(env[`${prefix}_HEADERS`]!) : {},
      secrets,
    });
  }

  private storeCookies(res: Response): void {
    const list = typeof (res.headers as any).getSetCookie === "function" ? (res.headers as any).getSetCookie() : [];
    for (const raw of list as string[]) {
      const [pair] = raw.split(";");
      const i = pair.indexOf("=");
      if (i > 0) this.cookies[pair.slice(0, i).trim()] = pair.slice(i + 1).trim();
    }
  }

  private async send(method: string, path: string, opts: RequestOptions): Promise<Response> {
    const url = new URL(this.baseUrl + path);
    for (const [k, v] of Object.entries(opts.query ?? {})) {
      if (v !== undefined && v !== null) url.searchParams.set(k, String(v));
    }
    const headers: Record<string, string> = { ...this.headers };
    if (opts.auth !== false && this.token) {
      if (AUTH_KIND === "query" && AUTH_QUERY_PARAM) url.searchParams.set(AUTH_QUERY_PARAM, this.token);
      else if (AUTH_KIND === "basic") headers["Authorization"] = `Basic ${this.token}`;
      else if (AUTH_KIND === "bearer" || AUTH_KIND === "header") {
        headers[AUTH_HEADER ?? "Authorization"] = AUTH_SCHEME ? `${AUTH_SCHEME} ${this.token}` : this.token;
      }
    }
    for (const pair of CSRF_PAIRS) {
      if (this.cookies[pair.cookie]) headers[pair.header] = this.cookies[pair.cookie];
    }
    const cookie = Object.entries(this.cookies).map(([k, v]) => `${k}=${v}`).join("; ");
    if (cookie) headers["Cookie"] = cookie;
    let body: string | undefined;
    if (opts.body !== undefined) {
      if (opts.bodyKind === "form") {
        headers["Content-Type"] = "application/x-www-form-urlencoded";
        body = new URLSearchParams(opts.body as Record<string, string>).toString();
      } else {
        headers["Content-Type"] = "application/json";
        body = JSON.stringify(opts.body);
      }
    }
    const res = await this.fetchImpl(url, { method, headers, body, redirect: "manual" });
    this.storeCookies(res);
    return res;
  }

  private async runTokenFlow(flow: TokenFlow, values: Record<string, unknown>): Promise<Record<string, unknown>> {
    const prefetched: Record<string, unknown> = {};
    for (const pre of flow.prerequisites ?? []) {
      const res = await this.send(pre.method, pre.path, { auth: false });
      const text = await res.text();
      for (const [name, source] of Object.entries(pre.values)) {
        if (source.cookie) prefetched[`secret:${name}`] = this.cookies[source.cookie];
        else if (source.json) {
          try { prefetched[`secret:${name}`] = getPath(JSON.parse(text), source.json); } catch { /* not JSON */ }
        }
      }
    }
    const secretValues = Object.fromEntries(Object.entries(this.secrets).map(([k, v]) => [`secret:${k}`, v]));
    const body = fill(flow.template, { ...prefetched, ...secretValues, ...values });
    const res = await this.send(flow.method, flow.path, { body, bodyKind: flow.bodyKind, auth: false });
    const text = await res.text();
    if (res.status >= 400) throw new ApiError(res.status, text, flow.method, flow.path);
    let data: Record<string, unknown> = {};
    try { data = text ? JSON.parse(text) : {}; } catch { data = {}; }
    if (AUTH_KIND === "cookie" && SESSION_COOKIES.length && !SESSION_COOKIES.some((c) => this.cookies[c])) {
      throw new Error(`${flow.path} did not set a session cookie (${SESSION_COOKIES.join(", ")}); check the credentials`);
    }
    const token = getPath(data, flow.accessTokenPath);
    if (typeof token === "string") {
      this.token = token;
      const expiresIn = getPath(data, flow.expiresInPath);
      this.tokenExpiresAt = typeof expiresIn === "number" ? Date.now() + expiresIn * 1000 : jwtExp(token);
    }
    const refresh = getPath(data, flow.refreshTokenPath);
    if (typeof refresh === "string") this.refreshToken = refresh;
    return data;
  }

  /** Authenticate via the observed login flow. */
  async login(username?: string, password?: string): Promise<Record<string, unknown>> {
    if (!LOGIN_FLOW) throw new Error("no login flow was observed for this API");
    this.username = username ?? this.username;
    this.password = password ?? this.password;
    return this.runTokenFlow(LOGIN_FLOW, { username: this.username, password: this.password });
  }

  /** Obtain a new access token via the observed refresh flow. */
  async refresh(): Promise<Record<string, unknown>> {
    if (!REFRESH_FLOW) throw new Error("no refresh flow was observed for this API");
    return this.runTokenFlow(REFRESH_FLOW, { refresh_token: this.refreshToken });
  }

  private async reauthenticate(): Promise<boolean> {
    try {
      if (REFRESH_FLOW && this.refreshToken) { await this.refresh(); return true; }
      if (LOGIN_FLOW && this.username && this.password) { await this.login(); return true; }
    } catch {
      return false;
    }
    return false;
  }

  protected async request(method: string, path: string, opts: RequestOptions): Promise<unknown> {
    if (opts.auth !== false && this.autoRefresh && this.tokenExpiresAt && Date.now() > this.tokenExpiresAt - 30_000) {
      await this.reauthenticate();
    }
    let res = await this.send(method, path, opts);
    if ((res.status === 401 || res.status === 403) && opts.auth !== false && this.autoRefresh && (await this.reauthenticate())) {
      res = await this.send(method, path, opts);
    }
    const text = await res.text();
    if (!res.ok) throw new ApiError(res.status, text, method, path);
    if (opts.expect === "empty" || !text) return undefined;
    if (opts.expect === "json" || (res.headers.get("content-type") ?? "").includes("json")) {
      try { return JSON.parse(text); } catch { return text; }
    }
    return text;
  }

  protected async graphql(method: string, path: string, operation: string, variables: unknown, auth: boolean): Promise<unknown> {
    const spec = GRAPHQL_OPERATIONS[operation] ?? { query: null, extensions: null };
    const payload: Record<string, unknown> = { operationName: operation, variables: variables ?? {} };
    if (spec.query) payload.query = spec.query;
    if (spec.extensions) payload.extensions = spec.extensions;
    const call = () =>
      method === "GET"
        ? this.request("GET", path, {
            query: Object.fromEntries(Object.entries(payload).map(([k, v]) => [k, typeof v === "string" ? v : JSON.stringify(v)])),
            auth, expect: "json",
          })
        : this.request(method, path, { body: payload, bodyKind: "json", auth, expect: "json" });
    let result = (await call()) as Record<string, unknown>;
    const errorsOnly = (r: Record<string, unknown>) => Array.isArray(r?.errors) && r.errors.length > 0 && !r.data;
    if (errorsOnly(result)) {
      const text = JSON.stringify(result.errors).toLowerCase();
      const authError = ["unauth", "forbidden", "token", "login", "credential"].some((w) => text.includes(w));
      if (auth && authError && this.autoRefresh && (await this.reauthenticate())) result = (await call()) as Record<string, unknown>;
      if (errorsOnly(result)) throw new GraphQLError(operation, result.errors as unknown[]);
    }
    return result;
  }

  // ---- endpoints (one per observed endpoint) ----
"""
