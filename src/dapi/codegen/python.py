"""Python (httpx) client generator."""

from __future__ import annotations

import json
from typing import Any

from dapi.codegen.spec import ClientSpec, Operation, TokenFlow, pascal
from dapi.codegen.types import TypeRegistry

PRIM = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "null": "None"}


def py_type(node: Any) -> str:
    kind = node[0]
    if kind == "prim":
        return PRIM[node[1]]
    if kind == "list":
        return f"list[{py_type(node[1])}]"
    if kind == "map":
        return f"dict[str, {py_type(node[1])}]"
    if kind == "model":
        return node[1]
    if kind == "union":
        parts = list(dict.fromkeys(py_type(n) for n in node[1]))
        if "Any" in parts:
            return "Any"
        return " | ".join(sorted(parts, key=lambda p: p == "None"))
    return "Any"


def _param_type(t: str) -> str:
    return {"integer": "int", "number": "float", "boolean": "bool"}.get(t, "str")


def _doc(lines: list[str], indent: str) -> str:
    body = "\n".join((indent + line) if line else "" for line in lines)
    body = body.replace('"""', "'''").replace("\\", "\\\\")
    return f'{indent}"""{body.lstrip()}\n{indent}"""\n'


def _token_flow_literal(tf: TokenFlow | None) -> str:
    if tf is None:
        return "None"
    data = {
        "method": tf.method,
        "path": tf.path,
        "body_kind": tf.body_kind,
        "template": tf.template,
        "access_token_path": tf.access_token_path,
        "refresh_token_path": tf.refresh_token_path,
        "expires_in_path": tf.expires_in_path,
        "secret_params": tf.secret_params,
        "prerequisites": tf.prerequisites,
        "evidence_flows": tf.evidence,
    }
    return repr(json.loads(json.dumps(data)))


def generate_python(spec: ClientSpec) -> str:
    reg = TypeRegistry()
    op_types: dict[str, tuple[str, str | None]] = {}
    for op in spec.operations:
        resp = (
            py_type(reg.node(op.response_schema, pascal(op.name) + "Response"))
            if op.response_kind == "json"
            else ("None" if op.response_kind == "empty" else "str")
        )
        body = py_type(reg.node(op.body_schema, pascal(op.name) + "Request")) if op.body_kind else None
        op_types[op.name] = (resp, body)

    a = spec.auth
    out: list[str] = []
    w = out.append
    w(
        f'"""{spec.title} API client -- generated by dapi from {spec.flow_count} observed flows of {spec.origin}.\n\n'
    )
    w("Every method corresponds to an endpoint seen in captured traffic; docstrings cite the flows\n")
    w("that evidence it. Credentials are never embedded: pass them in, use from_env(), or from_dapi().\n\n")
    w(f"Regenerate: dapi generate --lang python --origin {spec.origin}\n")
    w('"""\n\n')
    w("from __future__ import annotations\n\n")
    w(
        "import base64\nimport json as _json\nimport os\nimport time\nfrom typing import Any, NotRequired, TypedDict\nfrom urllib.parse import quote\n\n"
    )
    w("import httpx\n\n")
    w(f"BASE_URL = {spec.origin!r}\n")
    w(f"ENV_PREFIX = {spec.env_prefix!r}\n")
    w(f"AUTH_KIND = {a.kind!r}  # inferred from observed traffic\n")
    w(f"AUTH_HEADER = {a.header_name!r}\n")
    w(f"AUTH_SCHEME = {a.scheme!r}\n")
    w(f"AUTH_QUERY_PARAM = {a.query_name!r}\n")
    w(f"SESSION_COOKIES = {a.cookie_names!r}\n")
    w(f"LOGIN_FLOW: dict[str, Any] | None = {_token_flow_literal(a.login)}\n")
    w(f"REFRESH_FLOW: dict[str, Any] | None = {_token_flow_literal(a.refresh)}\n")
    w(f"CSRF_PAIRS: list[dict[str, str]] = {a.csrf!r}  # header <- cookie echo, observed\n")
    w(f"TOKEN_LIFETIME_SECONDS: float | None = {a.lifetime_seconds!r}\n")
    gql_docs = {
        o.graphql["operation_name"]: {
            "query": o.graphql.get("document"),
            "extensions": o.graphql.get("extensions"),
        }
        for o in spec.operations
        if o.graphql
    }
    w(f"GRAPHQL_OPERATIONS: dict[str, dict[str, Any]] = {gql_docs!r}  # observed documents\n\n")
    if a.notes:
        w("# Auth evidence (from dapi auth analysis):\n")
        for n in a.notes[:12]:
            w(f"#   - {n}\n")
        w("\n")

    w(
        "\n# ---- Models inferred from observed payloads (keys absent in some samples are NotRequired) ----\n\n"
    )
    for m in reg.models:
        fields = ", ".join(
            f"{k!r}: {py_type(t) if req else f'NotRequired[{py_type(t)}]'}" for k, t, req in m.fields
        )
        w(f"{m.name} = TypedDict({m.name!r}, {{{fields}}})\n")
    w("\n\n")
    w(RUNTIME.replace("__CLASS__", spec.class_name))
    for op in spec.operations:
        w(_render_op(op, *op_types[op.name]))
    w(
        "\n\n__all__ = ["
        + ", ".join(
            repr(x) for x in [spec.class_name, "ApiError", "GraphQLError", *(m.name for m in reg.models)]
        )
        + "]\n"
    )
    return "".join(out)


def _render_graphql_op(op: Operation, resp_type: str, body_type: str | None) -> str:
    g = op.graphql or {}
    var_type = body_type or "dict[str, Any]"
    default = "" if op.body_required else " | None = None"
    auth = "False" if op.auth_required == "no" else "True"
    return (
        f"\n    def {op.name}(self, variables: {var_type}{default}) -> {resp_type}:\n"
        + _doc(op.doc, "        ")
        + f"        return self._graphql({op.method!r}, {op.path!r}, {g['operation_name']!r}, variables, auth={auth})\n"
    )


def _render_op(op: Operation, resp_type: str, body_type: str | None) -> str:
    if op.graphql:
        return _render_graphql_op(op, resp_type, body_type)
    args = ["self"]
    for p in op.path_params:
        args.append(f"{p.name}: {_param_type(p.type)} | str")
    if op.body_kind:
        args.append(f"body: {body_type or 'dict[str, Any]'}" + ("" if op.body_required else " | None = None"))
    kw = []
    for q in op.query_params:
        kw.append(f"{q.name}: {_param_type(q.type)} | None = None")
    kw.append("extra_params: dict[str, Any] | None = None")
    sig = ", ".join(args + ["*"] + kw)
    path_expr = op.path
    for p in op.path_params:
        path_expr = path_expr.replace("{" + p.wire + "}", "{_seg(" + p.name + ")}")
    lines = [f"\n    def {op.name}({sig}) -> {resp_type}:\n", _doc(op.doc, "        ")]
    params = ", ".join(f"{q.wire!r}: {q.name}" for q in op.query_params)
    lines.append(f"        params: dict[str, Any] = {{{params}}}\n")
    body_arg = ""
    if op.body_kind == "json":
        body_arg = ", json=body"
    elif op.body_kind == "form":
        body_arg = ", data=body"
    auth = "False" if op.auth_required == "no" else "True"
    path_lit = ("f" if "{" in path_expr else "") + repr(path_expr)
    lines.append(
        f"        return self._request({op.method!r}, {path_lit}, params=params, extra_params=extra_params"
        f"{body_arg}, auth={auth}, expect={op.response_kind!r})\n"
    )
    return "".join(lines)


