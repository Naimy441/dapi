class ApiError(Exception):
    """Raised for non-2xx responses."""

    def __init__(self, response: httpx.Response):
        self.response = response
        self.status_code = response.status_code
        super().__init__(f"{response.request.method} {response.request.url.path} -> {response.status_code}: {response.text[:300]}")


def _seg(value: Any) -> str:
    return quote(str(value), safe="")


def _get_path(data: Any, path: list[str] | None) -> Any:
    if path is None:
        return None
    for key in path:
        if not isinstance(data, dict):
            return None
        data = data.get(key)
    return data


def _fill(template: Any, values: dict[str, Any]) -> Any:
    if isinstance(template, dict):
        return {k: _fill(v, values) for k, v in template.items()}
    if isinstance(template, list):
        return [_fill(v, values) for v in template]
    if isinstance(template, str) and template.startswith("{{") and template.endswith("}}"):
        key = template[2:-2]
        if values.get(key) is None:
            raise ValueError(f"missing value for {key!r} (pass it to the client or set the env var)")
        return values[key]
    return template


def _jwt_exp(token: str | None) -> float | None:
    try:
        payload = token.split(".")[1]  # type: ignore[union-attr]
        claims = _json.loads(base64.urlsafe_b64decode(payload + "=" * (-len(payload) % 4)))
        return float(claims["exp"])
    except Exception:
        return None


class __CLASS__:
    """Client for endpoints observed at BASE_URL.

    Auth: credentials are applied according to AUTH_KIND. If a request is rejected with 401/403
    (or the token is about to expire) the client refreshes via the observed refresh flow, or logs in
    again via the observed login flow when username/password are available, then retries once.
    """

    def __init__(
        self,
        base_url: str = BASE_URL,
        *,
        token: str | None = None,
        refresh_token: str | None = None,
        username: str | None = None,
        password: str | None = None,
        cookies: dict[str, str] | None = None,
        headers: dict[str, str] | None = None,
        secrets: dict[str, str] | None = None,
        timeout: float = 30.0,
        auto_refresh: bool = True,
        http: httpx.Client | None = None,
    ):
        self.base_url = base_url.rstrip("/")
        self.token = token
        self.refresh_token = refresh_token
        self.username = username
        self.password = password
        self.secrets = dict(secrets or {})
        self.auto_refresh = auto_refresh
        self.token_expires_at: float | None = _jwt_exp(token)
        self._http = http or httpx.Client(base_url=self.base_url, timeout=timeout, headers=headers or {})
        for name, value in (cookies or {}).items():
            self._http.cookies.set(name, value)

    # -- construction helpers ----------------------------------------------------------------
    @classmethod
    def from_env(cls, prefix: str = ENV_PREFIX, **kwargs: Any) -> "__CLASS__":
        """Read <PREFIX>_BASE_URL, _TOKEN, _REFRESH_TOKEN, _USERNAME, _PASSWORD, _COOKIES (a Cookie
        header string), _HEADERS (JSON object) and _SECRET_<NAME> from the environment."""
        env = os.environ
        cookies = {}
        for part in (env.get(f"{prefix}_COOKIES") or "").split(";"):
            if "=" in part:
                k, v = part.strip().split("=", 1)
                cookies[k] = v
        secrets = {k[len(prefix) + 8:].lower(): v for k, v in env.items() if k.startswith(f"{prefix}_SECRET_")}
        return cls(
            env.get(f"{prefix}_BASE_URL", BASE_URL),
            token=env.get(f"{prefix}_TOKEN"),
            refresh_token=env.get(f"{prefix}_REFRESH_TOKEN"),
            username=env.get(f"{prefix}_USERNAME"),
            password=env.get(f"{prefix}_PASSWORD"),
            cookies=cookies or None,
            headers=_json.loads(env[f"{prefix}_HEADERS"]) if env.get(f"{prefix}_HEADERS") else None,
            secrets=secrets,
            **kwargs,
        )

    @classmethod
    def from_dapi(cls, workspace: str | None = None, **kwargs: Any) -> "__CLASS__":
        """Reuse the session dapi captured/verified (requires the dapi package and its workspace)."""
        from dapi.session import resolve_session
        from dapi.workspace import Workspace

        sess = resolve_session(Workspace(workspace) if workspace else Workspace(), BASE_URL)
        headers = dict(sess["headers"])
        token = None
        if AUTH_KIND in ("bearer", "header") and AUTH_HEADER:
            for name in list(headers):
                if name.lower() == AUTH_HEADER.lower():
                    value = headers.pop(name)
                    token = value.split(" ", 1)[1] if AUTH_SCHEME and " " in value else value
        kwargs.setdefault("refresh_token", sess.get("refresh_token"))
        return cls(kwargs.pop("base_url", BASE_URL), token=token, headers=headers, cookies=sess["cookies"], **kwargs)

    def close(self) -> None:
        self._http.close()

    def __enter__(self) -> "__CLASS__":
        return self

    def __exit__(self, *exc: Any) -> None:
        self.close()

    # -- auth -----------------------------------------------------------------------------------
    def _run_prerequisites(self, flow: dict[str, Any]) -> dict[str, Any]:
        """Fetch values (e.g. CSRF tokens) that the observed flow obtained from earlier responses."""
        values: dict[str, Any] = {}
        for pre in flow.get("prerequisites") or []:
            resp = self._http.request(pre["method"], pre["path"])
            data: Any = None
            for name, source in pre["values"].items():
                if "cookie" in source:
                    values[f"secret:{name}"] = self._http.cookies.get(source["cookie"])
                else:
                    if data is None:
                        try:
                            data = resp.json()
                        except ValueError:
                            data = {}
                    values[f"secret:{name}"] = _get_path(data, source["json"])
        return values

    def _csrf_headers(self) -> dict[str, str]:
        headers = {}
        for pair in CSRF_PAIRS:
            value = self._http.cookies.get(pair["cookie"])
            if value:
                headers[pair["header"]] = value
        return headers

    def _run_token_flow(self, flow: dict[str, Any], values: dict[str, Any]) -> dict[str, Any]:
        prefetched = self._run_prerequisites(flow)
        secrets = {f"secret:{k}": v for k, v in self.secrets.items()}
        body = _fill(flow["template"], {**prefetched, **secrets, **values})
        kwargs = {"json": body} if flow["body_kind"] == "json" else {"data": body}
        resp = self._http.request(flow["method"], flow["path"], headers=self._csrf_headers(), **kwargs)
        if resp.status_code >= 400:
            raise ApiError(resp)
        try:
            data = resp.json() if resp.content else {}
        except ValueError:
            data = {}
        if AUTH_KIND == "cookie" and SESSION_COOKIES and not any(self._http.cookies.get(c) for c in SESSION_COOKIES):
            raise RuntimeError(f"{flow['path']} did not set a session cookie {SESSION_COOKIES}; check the credentials")
        token = _get_path(data, flow.get("access_token_path"))
        if token:
            self.token = token
            expires_in = _get_path(data, flow.get("expires_in_path"))
            self.token_expires_at = (time.time() + float(expires_in)) if isinstance(expires_in, int | float) else _jwt_exp(token)
        new_refresh = _get_path(data, flow.get("refresh_token_path"))
        if new_refresh:
            self.refresh_token = new_refresh
        return data

    def login(self, username: str | None = None, password: str | None = None) -> dict[str, Any]:
        """Authenticate via the observed login flow (see LOGIN_FLOW evidence)."""
        if LOGIN_FLOW is None:
            raise RuntimeError("no login flow was observed for this API")
        self.username = username or self.username
        self.password = password or self.password
        return self._run_token_flow(LOGIN_FLOW, {"username": self.username, "password": self.password})

    def refresh(self) -> dict[str, Any]:
        """Obtain a new access token via the observed refresh flow (see REFRESH_FLOW evidence)."""
        if REFRESH_FLOW is None:
            raise RuntimeError("no refresh flow was observed for this API")
        return self._run_token_flow(REFRESH_FLOW, {"refresh_token": self.refresh_token})

    def _reauthenticate(self) -> bool:
        try:
            if REFRESH_FLOW is not None and self.refresh_token:
                self.refresh()
                return True
            if LOGIN_FLOW is not None and self.username and self.password:
                self.login()
                return True
        except (ApiError, ValueError, RuntimeError, httpx.HTTPError):
            return False
        return False

    def _auth_headers(self) -> dict[str, str]:
        if not self.token or AUTH_KIND in ("cookie", "query", "none"):
            return {}
        if AUTH_KIND == "basic":
            return {"Authorization": f"Basic {self.token}"}
        header = AUTH_HEADER or "Authorization"
        return {header: f"{AUTH_SCHEME} {self.token}" if AUTH_SCHEME else self.token}

    # -- transport ----------------------------------------------------------------------------
    def _request(self, method: str, path: str, *, params: dict[str, Any] | None = None,
                 extra_params: dict[str, Any] | None = None, json: Any = None, data: Any = None,
                 auth: bool = True, expect: str = "json") -> Any:
        query = {k: v for k, v in {**(params or {}), **(extra_params or {})}.items() if v is not None}
        if auth and AUTH_KIND == "query" and self.token:
            query[AUTH_QUERY_PARAM] = self.token
        if auth and self.auto_refresh and self.token_expires_at and time.time() > self.token_expires_at - 30:
            self._reauthenticate()

        def send() -> httpx.Response:
            headers = {**self._csrf_headers(), **(self._auth_headers() if auth else {})}
            return self._http.request(method, path, params=query or None, json=json, data=data, headers=headers)

        resp = send()
        if resp.status_code in (401, 403) and auth and self.auto_refresh and self._reauthenticate():
            resp = send()
        if resp.status_code >= 400:
            raise ApiError(resp)
        if expect == "empty" or not resp.content:
            return None
        if expect == "json" or "json" in resp.headers.get("content-type", ""):
            try:
                return resp.json()
            except ValueError:
                return resp.text
        return resp.text

    def _graphql(self, method: str, path: str, operation: str, variables: Any, *, auth: bool = True) -> Any:
        spec = GRAPHQL_OPERATIONS.get(operation, {})
        payload: dict[str, Any] = {"operationName": operation, "variables": variables or {}}
        if spec.get("query"):
            payload["query"] = spec["query"]
        if spec.get("extensions"):
            payload["extensions"] = spec["extensions"]

        def call() -> Any:
            if method == "GET":
                params = {k: v if isinstance(v, str) else _json.dumps(v) for k, v in payload.items()}
                return self._request("GET", path, params=params, auth=auth, expect="json")
            return self._request(method, path, json=payload, auth=auth, expect="json")

        result = call()
        errors = result.get("errors") if isinstance(result, dict) else None
        if errors and not result.get("data"):
            auth_error = any(
                w in _json.dumps(errors).lower() for w in ("unauth", "forbidden", "token", "login", "credential")
            )
            if auth and auth_error and self.auto_refresh and self._reauthenticate():
                result = call()
                errors = result.get("errors") if isinstance(result, dict) else None
            if errors and not result.get("data"):
                raise GraphQLError(operation, errors)
        return result

